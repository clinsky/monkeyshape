import { describe, expect, test } from "bun:test";
import { checkSources } from "../../src/core/sources.ts";
import type { ShapeConfig } from "../../src/schemas/config.ts";
import { config, repo } from "../support.ts";

const messages = (shape: ShapeConfig, files: Record<string, string>) =>
  checkSources(config(shape), repo(files)).map((v) => `${v.rule} ${v.file}: ${v.message}`);

describe("sources", () => {
  test("an exclude glob that matches nothing hides nothing, so it doesn't fail", () => {
    // Extending exclude restates the defaults, `.tsx` included, in a repo with none.
    expect(
      messages({ sources: { exclude: ["**/*.test.ts", "**/*.test.tsx"] } }, { "src/a.ts": "" }),
    ).toEqual([]);
  });

  test("an include or exempt glob that matches nothing still fails", () => {
    expect(
      messages(
        {
          sources: {
            include: ["src/**/*.ts", "lib/**/*.ts"],
            exempt: [{ path: "gen/**", reason: "generated by the build" }],
          },
        },
        { "src/a.ts": "" },
      ),
    ).toEqual([
      expect.stringContaining("`sources.include` lists 'lib/**/*.ts'"),
      expect.stringContaining("`sources.exempt` lists 'gen/**'"),
    ]);
  });

  test("a file excluded from include is told to move to exempt, not to add a glob it has", () => {
    const [message] = messages({ sources: { exclude: ["src/gen/**"] } }, { "src/gen/x.ts": "" });
    expect(message).toContain("removed by `sources.exclude`");
    expect(message).toContain("`sources.exempt`");
    expect(message).not.toContain("Add a glob");
  });

  test("the suggested glob matches the file's own extension", () => {
    expect(messages({}, { "lib/x.mts": "", "y.cts": "", "app/v.tsx": "" })).toEqual([
      expect.stringContaining("'lib/**/*.mts'"),
      expect.stringContaining("'*.cts'"),
      expect.stringContaining("'app/**/*.tsx'"),
    ]);
  });
});
